import io
from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st

st.set_page_config(
    page_title="SMARTWATT AI",
    page_icon="⚡",
    layout="wide"
)

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "smartwatt_anomaly_model.pkl"
SCALER_PATH = BASE_DIR / "smartwatt_scaler.pkl"
FEATURES_PATH = BASE_DIR / "smartwatt_features.pkl"

EXPECTED_FEATURES = [
    "energy_kwh",
    "lag_1",
    "lag_7",
    "rolling_mean_7",
    "rolling_std_7",
    "day_of_week"
]

@st.cache_resource
def load_artifacts():
    missing = [
        path.name for path in [MODEL_PATH, SCALER_PATH, FEATURES_PATH]
        if not path.exists()
    ]
    if missing:
        raise FileNotFoundError(
            "Missing model artifact(s): " + ", ".join(missing)
        )

    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    feature_names = joblib.load(FEATURES_PATH)

    if feature_names != EXPECTED_FEATURES:
        raise ValueError(
            "The saved feature list does not match the model's expected feature order. "
            f"Found: {feature_names}"
        )

    if getattr(scaler, "n_features_in_", None) != len(EXPECTED_FEATURES):
        raise ValueError("The saved scaler does not expect six input features.")

    if getattr(model, "n_features_in_", None) != len(EXPECTED_FEATURES):
        raise ValueError("The saved Isolation Forest does not expect six input features.")

    return model, scaler, feature_names


def prepare_model_features(raw_daily, feature_names):
    required_columns = {"date", "energy_kwh"}
    missing_columns = required_columns - set(raw_daily.columns)
    if missing_columns:
        raise ValueError(
            "CSV must contain these columns: date, energy_kwh. "
            f"Missing: {', '.join(sorted(missing_columns))}"
        )

    data = raw_daily[["date", "energy_kwh"]].copy()
    data["date"] = pd.to_datetime(data["date"], errors="coerce")
    data["energy_kwh"] = pd.to_numeric(data["energy_kwh"], errors="coerce")
    data = data.dropna(subset=["date", "energy_kwh"])
    data = data.sort_values("date").reset_index(drop=True)

    if data["date"].duplicated().any():
        raise ValueError(
            "The CSV contains duplicate dates. Please use the daily_energy.csv "
            "exported by the cleaned notebook."
        )

    if (data["energy_kwh"] < 0).any():
        raise ValueError("Energy consumption cannot be negative.")

    # Match the six features used during training.
    data["lag_1"] = data["energy_kwh"].shift(1)
    data["lag_7"] = data["energy_kwh"].shift(7)
    data["rolling_mean_7"] = (
        data["energy_kwh"].shift(1).rolling(window=7).mean()
    )
    data["rolling_std_7"] = (
        data["energy_kwh"].shift(1).rolling(window=7).std()
    )
    data["day_of_week"] = data["date"].dt.dayofweek

    # The training notebook first removed seven rows for lag/rolling features,
    # then removed another seven-row warm-up while building extra historical
    # columns. Preserve that same 14-row warm-up so app inputs match training.
    data = data.dropna().reset_index(drop=True)
    data = data.iloc[7:].reset_index(drop=True)

    if data.empty:
        raise ValueError(
            "Not enough daily observations. At least 15 valid daily rows are needed."
        )

    X = data[feature_names].copy()
    return data, X


st.title("⚡ SMARTWATT AI")
st.subheader("Electricity Consumption Anomaly Detection")
st.write(
    "Upload the `daily_energy.csv` file generated by the project notebook. "
    "The trained Improved Isolation Forest will classify each eligible day "
    "as Normal or Anomaly."
)

with st.expander("How the model works"):
    st.write(
        "The model uses six inputs: daily energy consumption, previous-day "
        "consumption, consumption seven observations earlier, previous "
        "seven-observation rolling mean and standard deviation, and day of week."
    )
    st.caption(
        "The first 14 rows are reserved as historical warm-up, matching the "
        "training notebook. Model agreement is not a verified accuracy score."
    )

try:
    model, scaler, feature_names = load_artifacts()
    st.success("Trained model, scaler, and feature list loaded.")
except Exception as exc:
    st.error(f"Could not load the model artifacts: {exc}")
    st.stop()

uploaded_file = st.file_uploader(
    "Upload daily_energy.csv",
    type=["csv"],
    help="CSV must contain date and energy_kwh columns."
)

if uploaded_file is not None:
    try:
        raw_data = pd.read_csv(uploaded_file)
        scored_data, X = prepare_model_features(raw_data, feature_names)

        X_scaled = scaler.transform(X)
        predictions = model.predict(X_scaled)
        scores = model.decision_function(X_scaled)

        results = scored_data[["date", "energy_kwh"]].copy()
        results["prediction"] = predictions
        results["status"] = results["prediction"].map({
            1: "Normal",
            -1: "Anomaly"
        })
        results["anomaly_score"] = scores

        anomaly_count = int((results["prediction"] == -1).sum())
        normal_count = int((results["prediction"] == 1).sum())
        total_count = len(results)

        st.markdown("### Detection summary")
        c1, c2, c3 = st.columns(3)
        c1.metric("Days analysed", total_count)
        c2.metric("Normal days", normal_count)
        c3.metric("Anomalies", anomaly_count)

        st.markdown("### Consumption timeline")
        fig, ax = plt.subplots(figsize=(12, 5))
        ax.plot(
            results["date"],
            results["energy_kwh"],
            label="Daily consumption",
            linewidth=1.5
        )

        normal_rows = results[results["prediction"] == 1]
        anomaly_rows = results[results["prediction"] == -1]

        ax.scatter(
            normal_rows["date"],
            normal_rows["energy_kwh"],
            label="Normal",
            s=24
        )
        ax.scatter(
            anomaly_rows["date"],
            anomaly_rows["energy_kwh"],
            label="Anomaly",
            marker="X",
            s=90
        )
        ax.set_xlabel("Date")
        ax.set_ylabel("Energy consumption (kWh)")
        ax.set_title("SMARTWATT AI – Detected consumption anomalies")
        ax.grid(True, alpha=0.3)
        ax.legend()
        fig.autofmt_xdate()
        st.pyplot(fig, use_container_width=True)
        plt.close(fig)

        st.markdown("### Detected anomalies")
        if anomaly_count:
            st.dataframe(
                results.loc[results["prediction"] == -1].sort_values("date"),
                use_container_width=True,
                hide_index=True
            )
        else:
            st.info("No anomalies were detected in the uploaded data.")

        with st.expander("View all predictions"):
            st.dataframe(
                results.sort_values("date"),
                use_container_width=True,
                hide_index=True
            )

        csv_bytes = results.to_csv(index=False).encode("utf-8")
        st.download_button(
            "Download anomaly results (CSV)",
            data=csv_bytes,
            file_name="smartwatt_anomaly_results.csv",
            mime="text/csv"
        )

        st.caption(
            "Anomaly labels are model predictions, not confirmed faults. "
            "Review flagged dates against actual household or meter conditions."
        )

    except Exception as exc:
        st.error(f"Could not process the uploaded CSV: {exc}")
else:
    st.info("Upload `daily_energy.csv` to run anomaly detection.")
